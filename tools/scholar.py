#!/usr/bin/env python3
"""Regenerate publications/publications.yml from Natalie's Google Scholar profile.

Google Scholar has no API: this reads the public profile page (100 rows per request, newest
first) and keeps what it lists: title, authors (Scholar truncates long lists with "..."),
venue, year, citation count and the Scholar link. The items feed the listing in
publications/index.qmd (template _templates/publications.ejs); publications/_metadata.yml gets
the date of the last change.

Nothing is written unless the fetch clearly worked: an HTTP error, a CAPTCHA / "unusual traffic"
page, a page without the profile, or fewer publications than the committed file (pass
--allow-shrink if one was really removed or merged on Scholar) exit with status 1 and leave the
files as they are. Files are rewritten only when the publications changed.

Deps: Python 3.9+, standard library only.
Run by .github/workflows/publications.yml every three months; locally: python tools/scholar.py
Usage: python tools/scholar.py [--user ID] [--allow-shrink] [--from-html FILE]
"""
import argparse, datetime, html, json, re, sys, time, urllib.error, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "publications" / "publications.yml"
META = ROOT / "publications" / "_metadata.yml"
USER = "pBv3_DoAAAAJ"
BASE = "https://scholar.google.com"
PAGE = 100
UA = ("Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) "
      "Chrome/130.0 Safari/537.36")


def fail(msg):
    print(f"scholar.py: {msg}; nothing written", file=sys.stderr)
    sys.exit(1)


def fetch(user, cstart):
    url = (f"{BASE}/citations?user={user}&hl=en&cstart={cstart}&pagesize={PAGE}"
           "&sortby=pubdate")
    req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept-Language": "en"})
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return r.read().decode("utf-8", "replace")
    except urllib.error.HTTPError as e:
        fail(f"HTTP {e.code} from Google Scholar (blocked or rate limited?)")
    except urllib.error.URLError as e:
        fail(f"could not reach Google Scholar ({e.reason})")


def text(fragment):
    return " ".join(html.unescape(re.sub(r"<[^>]+>", "", fragment)).split())


def parse(page):
    if re.search(r"captcha|unusual traffic", page, re.I):
        fail("Google Scholar answered with a CAPTCHA page")
    if 'id="gsc_prf_in"' not in page:
        fail("the response is not a Scholar profile page")
    pubs = []
    for row in re.findall(r'<tr class="gsc_a_tr">(.*?)</tr>', page, re.S):
        link = re.search(r'<a href="([^"]+)" class="gsc_a_at">(.*?)</a>', row, re.S)
        gray = re.findall(r'<div class="gs_gray">(.*?)</div>', row, re.S)
        if not link or len(gray) < 2:
            fail("unexpected row markup (did Scholar change its HTML?)")
        venue = text(re.sub(r'<span class="gs_oph">.*?</span>', "", gray[1], flags=re.S))
        cites = re.search(r'class="gsc_a_ac[^"]*">(\d+)<', row)
        year = re.search(r'class="gsc_a_h[^"]*">(\d{4})<', row)
        href = html.unescape(link.group(1))
        cid = re.search(r"citation_for_view=([^&]+)", href)
        pubs.append({
            "title": text(link.group(2)),
            "path": f"{BASE}/citations?view_op=view_citation&hl=en&citation_for_view={cid.group(1)}"
                    if cid else BASE + href,
            "authors": text(gray[0]),
            "venue": venue,
            "year": int(year.group(1)) if year else None,
            "citations": int(cites.group(1)) if cites else 0,
        })
    return pubs


def to_yaml(pubs):
    # JSON strings are valid YAML double-quoted scalars, so no YAML library is needed.
    lines = ["# Generated by tools/scholar.py from Google Scholar. Do not hand-edit."]
    for p in pubs:
        first = True
        for k, v in p.items():
            if v is None:
                continue
            lines.append(f"{'- ' if first else '  '}{k}: {json.dumps(v, ensure_ascii=False)}")
            first = False
    return "\n".join(lines) + "\n"


def committed_count():
    if not OUT.exists():
        return 0
    return sum(1 for l in OUT.read_text(encoding="utf-8").splitlines() if l.startswith("- "))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--user", default=USER, help="Scholar profile id (default: %(default)s)")
    ap.add_argument("--allow-shrink", action="store_true",
                    help="accept fewer publications than the committed file")
    ap.add_argument("--from-html", type=Path, help="parse a saved profile page instead of fetching")
    a = ap.parse_args()

    if a.from_html:
        pubs = parse(a.from_html.read_text(encoding="utf-8"))
    else:
        pubs, cstart = [], 0
        while True:
            batch = parse(fetch(a.user, cstart))
            pubs += batch
            if len(batch) < PAGE:
                break
            cstart += PAGE
            time.sleep(5)
    if not pubs:
        fail("the profile lists no publications")
    old = committed_count()
    if len(pubs) < old and not a.allow_shrink:
        fail(f"{len(pubs)} publications found but {old} are committed (use --allow-shrink)")

    # Newest first; Scholar's order is kept within a year, undated items go last.
    pubs.sort(key=lambda p: -(p["year"] or 0))
    new = to_yaml(pubs)
    if OUT.exists() and OUT.read_text(encoding="utf-8") == new:
        print(f"scholar.py: {len(pubs)} publications, no change")
        return
    OUT.write_text(new, encoding="utf-8")
    today = datetime.date.today()   # site date format, "MMM D, YYYY"
    META.write_text("# Generated by tools/scholar.py: date the publications list last changed.\n"
                    f"scholar-updated: \"{today:%b} {today.day}, {today.year}\"\n", encoding="utf-8")
    print(f"scholar.py: wrote {len(pubs)} publications to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
